"""Publish completed catalogue groups without replacing censored runs by successes."""
from pathlib import Path
import json
import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
GROUPS = [(30, 'perfect'), (100, 'perfect'), (300, 'perfect'),
          (1000, 'perfect'), (50, 'uncertain'), (500, 'uncertain')]
SUCCESS = 'reference_verified_convergence'


def completed_groups(outcomes: list[dict], count: int = 100) -> list[dict]:
    """Include whole groups only; keep unresolved outcomes in their denominator."""
    result = []
    for n, mode in GROUPS:
        rows = [r for r in outcomes if r['exposure'] == n and r['mode'] == mode]
        arms = {s: [r for r in rows if r['strategy'] == s] for s in ['bo', 'random']}
        for arm in arms.values():
            if len({r['case'] for r in arm}) != len(arm):
                raise ValueError('Duplicate catalogue outcome')
        if any(len(a) != count for a in arms.values()):
            continue
        group = {'expected': n, 'mode': mode, 'catalogues': count}
        for s, arm in arms.items():
            good = [r['points'] for r in arm if r['state'] == SUCCESS]
            group[s] = {'converged': len(good), 'unresolved': count-len(good),
                        'quantiles': np.quantile(good, [.1, .5, .9]).tolist()
                        if len(good) == count else None}
        result.append(group)
    return result


def main() -> None:
    source = HERE/'convergence_20260910/ensemble/outcomes.json'
    content = source.read_bytes()
    groups = completed_groups(json.loads(content))
    out = REPO/'overleaf/output/bo_study'
    out.mkdir(parents=True, exist_ok=True)
    (out/'convergence_outcomes_snapshot.json').write_bytes(content)
    (out/'convergence_summary.json').write_text(json.dumps(groups, indent=2)+'\n')
    lines = [r'% Generated by docs/studies/event_uncertainty/publish_convergence.py.',
        r'\begin{table*}\centering',
        r'\caption{Reference-assisted evaluation requirements for the accuracy and stability criteria in Eq.~\eqref{eq:convergence_metrics}, including marginal and numerical checks. These benchmark requirements use direct-reference information and are not operational stopping times. Entries give the median [10th--90th percentile] across 100 fresh Poisson catalogues per setting, at one fixed injection and acquisition seed per strategy. Both displayed groups have 100/100 converged catalogues for each method; remaining regimes are in progress. Counts include initialization and are resolved at batches of 128 evaluations.}',
        r'\begin{tabular}{rlrr}\toprule Expected detections & Measurements & BO & Random\\\midrule']
    for g in groups:
        cells = []
        for s in ['bo', 'random']:
            arm = g[s]
            if arm['quantiles'] is None:
                cells.append(f"{arm['unresolved']}/100 unresolved")
            else:
                lo, med, hi = arm['quantiles']
                cells.append(f'{med:g} [{lo:g}--{hi:g}]')
        lines.append(f"{g['expected']} & {g['mode'].capitalize()} & {cells[0]} & {cells[1]} "+r'\\')
    if any(g[s]['unresolved'] for g in groups for s in ['bo', 'random']):
        lines[2] = lines[2].replace('Both displayed groups have 100/100 converged catalogues for each method; remaining regimes are in progress.',
            'Unresolved runs are counted explicitly instead of assigning them a convergence time. Quantile summaries are shown only when all 100 catalogues converge; remaining regimes are in progress.')
    lines += [r'\bottomrule\end{tabular}\label{tab:bo_budgets}\end{table*}']
    (out/'convergence_table.tex').write_text('\n'.join(lines)+'\n')


if __name__ == '__main__':
    main()
