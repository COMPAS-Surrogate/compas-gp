def widths(summary):
 q=np.array(summary['quantiles']);return q[4]-q[2]
def fraction_by_budget(rows:list,points:np.ndarray,denominator:int)->np.ndarray:
 """Censored/unresolved cases do not disappear from a completion curve."""
 if len(rows)!=denominator:raise ValueError('Incomplete outcome group')
 if len({r['case'] for r in rows})!=denominator:raise ValueError('Duplicate cases')
 return np.array([sum(r['state']=='reference_verified_convergence' and r['points']<=p for r in rows)/denominator for p in points])
def ensemble_rows():
 rows=read(ROOT/'convergence_20260910/ensemble/outcomes.json')
 folder=HERE/'refined_case49_20260911'
 if (folder/'status.json').exists() and read(folder/'status.json')['state']=='complete':
  updates=read(folder/'outcomes.json');assert len(updates)==2
  for update in updates:
   matches=[i for i,r in enumerate(rows) if (r['exposure'],r['mode'],r['case'],r['strategy'])==(update['exposure'],update['mode'],update['case'],update['strategy'])]
   assert len(matches)==1 and rows[matches[0]]['state']=='reference_unresolved'
   rows[matches[0]]=dict(update,reference_followup=True)
 return rows

