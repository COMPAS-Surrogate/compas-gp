def information():
 pilot=read(ROOT/'results/records.json');refs=read(ROOT/'results/references.json')
 sweep=read(ROOT/'essential_20260910/sweep/records.json');sr=read(ROOT/'essential_20260910/sweep/references.json')
 # Direct and GP summaries at the same catalogue, measurement width and final budget.
 data=[]
 for n in [50,500]:
  for case in range(10):
   for scale in [0,.5,1,2]:
    if scale in [0,1]:
     mode='perfect' if scale==0 else 'uncertain'
     r=next(x for x in refs if (x['expected_events'],x['case'],x['mode'])==(n,case,mode))
     g=next(x for x in pilot if (x['expected_events'],x['case'],x['mode'],x['strategy'],x['points'])==(n,case,mode,'bo',738))
    else:
     r=next(x for x in sr if not x.get('control') and (x['exposure'],x['case'],x['scale'])==(n,case,scale))
     g=next(x for x in sweep if (x['exposure'],x['case'],x['scale'],x['strategy'],x['points'])==(n,case,scale,'bo',738))
    # Completed independent refinements replace estimates, preserving raw originals.
    if (n,case,scale)==(500,8,2):
     f=HERE/'reference_refinement_20260911/width_records.json';c=HERE/'reference_refinement_20260911/reference_checks.json'
     if f.exists():
      g=next(x for x in read(f) if x['strategy']=='bo');r=[x for x in read(c) if x['study']=='double_width'][-1]
    if (n,case,scale)==(500,8,1):
     f=ROOT/'essential_20260910/refine/records.json';c=ROOT/'essential_20260910/refine/references.json'
     g=next(x for x in read(f) if x['strategy']=='bo' and x['points']==738);r=read(c)[0]
    data.append(dict(expected=n,case=case,scale=scale,direct=widths(r['summaries'][0]).tolist(),gp=widths(g['summaries'][0]).tolist(),numerical_pass=bool(r.get('numerical_pass',True) and g.get('numerical_pass',True))))
